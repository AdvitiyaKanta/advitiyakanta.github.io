/* Regenerates js/image-meta.js from the files actually present in assets/.
   Intrinsic dimensions prevent layout shift on generated project pages. */
import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const assetsRoot = path.join(root, "assets");

function readSize(file) {
  const buffer = fs.readFileSync(file);
  if (buffer.slice(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) {
    return [buffer.readUInt32BE(16), buffer.readUInt32BE(20)];
  }
  if (buffer[0] === 0xff && buffer[1] === 0xd8) {
    let offset = 2;
    while (offset < buffer.length) {
      if (buffer[offset] !== 0xff) { offset += 1; continue; }
      const marker = buffer[offset + 1];
      if (marker === 0xd8 || marker === 0x01 || (marker >= 0xd0 && marker <= 0xd7)) { offset += 2; continue; }
      const length = buffer.readUInt16BE(offset + 2);
      if (marker >= 0xc0 && marker <= 0xcf && marker !== 0xc4 && marker !== 0xc8 && marker !== 0xcc) {
        return [buffer.readUInt16BE(offset + 7), buffer.readUInt16BE(offset + 5)];
      }
      offset += 2 + length;
    }
  }
  return null;
}

const entries = [];
function walk(directory) {
  for (const name of fs.readdirSync(directory).sort()) {
    const full = path.join(directory, name);
    if (fs.statSync(full).isDirectory()) { walk(full); continue; }
    if (!/\.(jpe?g|png)$/i.test(name)) continue;
    const size = readSize(full);
    if (!size) continue;
    entries.push([path.relative(root, full).split(path.sep).join("/"), size]);
  }
}
walk(assetsRoot);

const body = entries.map(([key, [w, h]]) => `  "${key}": [${w}, ${h}],`).join("\n");
fs.writeFileSync(
  path.join(root, "js", "image-meta.js"),
  `/* Generated by scripts/build-image-meta.mjs. Intrinsic media dimensions\n   prevent layout shift on generated project pages. */\nconst IMAGE_META = {\n${body}\n};\n`
);
console.log(`Wrote js/image-meta.js with ${entries.length} entries.`);
